#!/usr/bin/env bash
# Build the Forerunner 245 app: garmin/bin/HealthHubGym.prg
#   garmin/scripts/build.sh [device]      (default fr245)
# Needs: Java, the Connect IQ SDK (CIQ_SDK or ~/.garmin/sdk-*), the device files
# (connect-iq-sdk-manager device download), and SYNC_TOKEN in the repo's .env.local.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$here/.." && pwd)"
device="${1:-fr245}"
sdk="${CIQ_SDK:-$(ls -d "$HOME"/.garmin/sdk-* 2>/dev/null | sort -V | tail -1)}"
[[ -x "$sdk/bin/monkeyc" ]] || { echo "Connect IQ SDK not found (set CIQ_SDK)"; exit 1; }

env_file="${ENV_FILE:-$repo/.env.local}"
[[ -f "$env_file" ]] || env_file="/home/dwrzl/health-hub/.env.local"
sync_token="$(grep -E '^SYNC_TOKEN=' "$env_file" | head -1 | cut -d= -f2- | tr -d '"' | tr -d "'")"
[[ -n "$sync_token" ]] || { echo "SYNC_TOKEN missing from $env_file"; exit 1; }
base_url="${HEALTH_HUB_URL:-$(grep -E '^HEALTH_HUB_URL=' "$env_file" | head -1 | cut -d= -f2- | tr -d '"' || true)}"
base_url="${base_url:-https://health-hub-topaz-sigma.vercel.app}"
wrist_token="$(cd "$repo" && SYNC_TOKEN="$sync_token" node -e "import('./lib/wrist-route.mjs').then(m=>process.stdout.write(m.wristToken(process.env.SYNC_TOKEN)))")"

umask 077
cat > "$here/secrets/Secrets.mc" <<MC
// Generated by garmin/scripts/build.sh. Do not commit.
module Secrets {
    const WRIST_URL = "${base_url%/}/api/wrist";
    const WRIST_TOKEN = "$wrist_token";
}
MC

key="$here/developer_key.der"
if [[ ! -f "$key" ]]; then
  openssl genrsa -out "$here/developer_key.pem" 4096 2>/dev/null
  openssl pkcs8 -topk8 -inform PEM -outform DER -in "$here/developer_key.pem" -out "$key" -nocrypt
fi

mkdir -p "$here/bin"
"$sdk/bin/monkeyc" -d "$device" -f "$here/monkey.jungle" -o "$here/bin/HealthHubGym.prg" -y "$key" -w
echo "Built $here/bin/HealthHubGym.prg for $device"
